def normalize_mac(mac: str) -> str:
    """Normalize MAC address into uppercase XX:XX:XX:XX:XX:XX format."""
    clean = re.sub(r"[^0-9a-fA-F]", "", mac).upper()
    if len(clean) != 12:
        return mac.upper()
    return ":".join(clean[i : i + 2] for i in range(0, 12, 2))


def lookup_vendor(mac: str) -> str:
    """Resolve the hardware vendor from the MAC OUI prefix."""
    if not mac or mac in {"?", "00:00:00:00:00:00", "FF:FF:FF:FF:FF:FF"}:
        return "Unknown"
    norm = normalize_mac(mac)
    prefix = norm[:8]
    if prefix in _OUI_DATABASE:
        return _OUI_DATABASE[prefix]
    
    # Check if locally administered / randomized MAC (bit 1 of 1st byte is set)
    try:
        first_byte = int(norm[:2], 16)
        if first_byte & 0x02:
            return "Private / Randomized MAC"
        if first_byte & 0x01:
            return "Multicast / Broadcast"
    except Exception:
        pass

    return "Generic Vendor"
